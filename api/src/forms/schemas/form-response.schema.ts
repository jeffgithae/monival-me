import { Prop, Schema, SchemaFactory } from '@nestjs/mongoose';
import { HydratedDocument, Types, SchemaTypes } from 'mongoose';

export type FormResponseDocument = HydratedDocument<FormResponse>;

@Schema({ timestamps: true })
export class FormResponse {
  @Prop({ type: SchemaTypes.ObjectId, ref: 'Organization', required: true, index: true })
  organizationId!: Types.ObjectId;

  @Prop({ type: SchemaTypes.ObjectId, ref: 'Project', required: true, index: true })
  projectId!: Types.ObjectId;

  @Prop({ type: SchemaTypes.ObjectId, ref: 'FormTemplate', required: true, index: true })
  templateId!: Types.ObjectId;

  @Prop({ type: SchemaTypes.ObjectId, ref: 'Indicator', index: true })
  indicatorId?: Types.ObjectId;

  @Prop({ type: SchemaTypes.ObjectId, ref: 'Activity', index: true })
  activityId?: Types.ObjectId;

  @Prop({ type: SchemaTypes.ObjectId, ref: 'User', index: true })
  submittedByUserId?: Types.ObjectId;

  @Prop({ type: Date, default: Date.now })
  collectedAt!: Date;

  @Prop({ type: Object, default: {} })
  answers!: Record<string, unknown>;

  @Prop({ type: String, enum: ['draft', 'submitted'], default: 'submitted' })
  status!: string;

  /**
   * Review state, mirroring Activity.status.
   *
   * A response only contributes to indicator achievement once approved —
   * the same "nothing counts toward a target until an M&E officer approves
   * it" rule that governs activities. Set either by the form-response
   * workflow outcome or by a direct review.
   */
  @Prop({ type: String, enum: ['pending', 'approved', 'rejected'], default: 'pending', index: true })
  approvalStatus!: string;

  @Prop({ type: SchemaTypes.ObjectId, ref: 'User' })
  reviewedByUserId?: Types.ObjectId;

  @Prop({ type: Date })
  reviewedAt?: Date;

  @Prop({ trim: true })
  rejectionReason?: string;

  /**
   * Numeric contribution extracted from `answers` at review time, using the
   * template's `indicatorValueKey`. Denormalised so indicator aggregation is
   * a plain `$sum` rather than a per-document key lookup.
   */
  @Prop({ type: Number, default: 0 })
  indicatorValue!: number;

  // ── Offline sync ───────────────────────────────────────────────────────────
  // clientId is a UUID generated by the mobile PWA before the record is
  // persisted, used as an idempotency key for offline-sync batches — see the
  // same pattern on Activity (activities/schemas/activity.schema.ts).
  @Prop({ trim: true, sparse: true })
  clientId?: string;

  @Prop({ type: Boolean, default: false })
  syncedFromOffline!: boolean;
}

export const FormResponseSchema = SchemaFactory.createForClass(FormResponse);

// ─── Indexes ──────────────────────────────────────────────────────────────────
FormResponseSchema.index({ organizationId: 1, templateId: 1, createdAt: -1 });
FormResponseSchema.index({ organizationId: 1, projectId: 1 });
FormResponseSchema.index({ 'answers.__integrationId': 1, 'answers.__externalId': 1 });
// Partial unique index: only enforce uniqueness when clientId is present.
FormResponseSchema.index(
  { organizationId: 1, clientId: 1 },
  {
    unique: true,
    name: 'org_clientId_unique',
    partialFilterExpression: { clientId: { $exists: true, $type: 'string', $gt: '' } },
  },
);
// Indicator aggregation reads approved responses for one indicator.
FormResponseSchema.index({ organizationId: 1, indicatorId: 1, approvalStatus: 1 });
// Reporting-period calculation windows on collection date.
FormResponseSchema.index({ organizationId: 1, projectId: 1, approvalStatus: 1, collectedAt: -1 });
